import { toDateKey } from './model.js';

function at(daysAgo, hour = 22, minute = 18) {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  date.setHours(hour, minute, 0, 0);
  return date;
}

function iso(daysAgo, hour = 22, minute = 18) {
  return at(daysAgo, hour, minute).toISOString();
}

function key(daysAgo) {
  return toDateKey(at(daysAgo));
}

